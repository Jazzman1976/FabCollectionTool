/*
 * build-fabrary-map.mjs - maintenance tool, not needed by users of the app.
 * Generates the shipped Fabrary mapping reference/fabrary-map.js from a collection export of
 * Fabrary (issue #17, addendum): wherever Fabrary names a set, an identifier or a treatment
 * differently from the rules of the export, the mapping holds Fabrary's name. Only clear
 * findings are taken; unclear ones and printings Fabrary does not know are listed.
 *
 * Usage:
 *   node tools/build-fabrary-map.mjs [fabrary-export.csv]
 * Without a file the export at the fixed local place .ignore/ressources/fabrary-export.csv
 * is taken (issue #31).
 */
import fs from 'node:fs';
import path from 'node:path';
import { loadApp, appRoot, fabraryExportFile } from './load-app.mjs';

// Read the command line: the file given, otherwise the one at the fixed local place.
const fabraryFile = process.argv[2] ||
    (fs.existsSync(fabraryExportFile) ? fabraryExportFile : '');
if (!fabraryFile) {
    console.error('Usage: node tools/build-fabrary-map.mjs [fabrary-export.csv]');
    console.error('Without a file the export at .ignore/ressources/fabrary-export.csv is ' +
        'taken; there is none.');
    process.exit(1);
}
console.log(`Fabrary export: ${fabraryFile}`);

// Load the app with the reference data; the comparison starts without any mapping.
const FCT = loadApp({ withReference: true, extra: ['app/model.js', 'app/fabrary-map.js',
    'app/export-fabrary.js'] });
FCT.reference.install(FCT.DATA, FCT.DATA.info);
const map = FCT.fabraryMap;
const none = map.empty();
const result = map.compare(FCT.exportFabrary.baseRows(), fs.readFileSync(fabraryFile, 'utf8'),
    none, none);
if (result.error) {
    console.error(result.error);
    process.exit(1);
}

// Collect the clear findings as a mapping.
const built = map.empty();
result.sets.forEach((s) => { built.sets[s.code] = s.fabrary; });
result.variants.forEach((v) => map.setVariant(built, v.row, v.fabrary, none));

// Write the file with one entry per line, so that Git diffs stay readable.
const entries = (object) => Object.keys(object).sort().map((k) =>
    `        ${JSON.stringify(k)}: ${JSON.stringify(object[k])}`).join(',\n');
const lines = [
    '/* Fabrary mapping: sets: { set code: Fabrary set name },',
    '   variants: { key: { identifier, set, treatment } },',
    '   key: set number | edition | foiling | treatments | identifier */',
    '/* Generated by tools/build-fabrary-map.mjs - do not edit by hand. */',
    `/* Source: ${path.basename(fabraryFile)} */`,
    'FCT.DATA.fabraryMap = {',
    '    sets: {',
    entries(built.sets),
    '    },',
    '    variants: {',
    entries(built.variants),
    '    }',
    '};',
    ''
];
fs.writeFileSync(path.join(appRoot, 'reference', 'fabrary-map.js'), lines.join('\n'), 'utf8');

// Report what was found and what was left out.
console.log(`fabrary-map.js: ${Object.keys(built.sets).length} sets, ` +
    `${Object.keys(built.variants).length} variants`);
console.log(`${result.matched} rows found in Fabrary's export, ` +
    `${result.notInFabrary.length} not there, ${result.unclear.length} unclear`);
const describe = (row) => row.identity.slice(4, 7).concat(row.art, row.identity[1])
    .filter(Boolean).join(' / ');
result.unclear.forEach((u) => console.log(`  unclear: ${describe(u.row)} -> ` +
    u.candidates.map((c) => c.identifier + ' | ' + c.treatment).join(' ; ')));
result.notInFabrary.slice(0, 20).forEach((row) => console.log(`  not in Fabrary: ` +
    describe(row)));
