/*
 * build-reference.mjs - maintenance tool, not needed by users of the app.
 * Generates the shipped reference data files reference/*.js from
 *   - the tab separated source files of the-fab-cube/flesh-and-blood-cards (csvs/english)
 * The Fabrary export needs no input of its own: it is built from the same data (issue #17).
 *
 * Usage:
 *   node tools/build-reference.mjs
 *       <folder with set.csv, set-printing.csv, card.csv, card-printing.csv>
 *       [commit-sha] [commit-date]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadApp } from './load-app.mjs';

const toolDir = path.dirname(fileURLToPath(import.meta.url));
const referenceDir = path.join(toolDir, '..', 'reference');

// Read the command line.
const [sourceDir, commit = '', commitDate = ''] = process.argv.slice(2);
if (!sourceDir) {
    console.error('Usage: node tools/build-reference.mjs <source folder>' +
        ' [commit-sha] [commit-date]');
    process.exit(1);
}

// Load the app scripts that contain the shared transformation code.
const FCT = loadApp();
const transform = FCT.referenceTransform;

// Transform the card data set.
const read = (file) => fs.readFileSync(path.join(sourceDir, file), 'utf8');
const data = transform.transform({
    set: read(transform.FILES.set),
    setPrinting: read(transform.FILES.setPrinting),
    card: read(transform.FILES.card),
    printing: read(transform.FILES.printing)
});

// Writes one data file with one record per line, so that Git diffs stay readable.
function writeData(file, comment, variable, records) {
    const lines = [
        `/* ${comment} */`,
        '/* Generated by tools/build-reference.mjs - do not edit by hand. */',
        `FCT.DATA.${variable} = [`,
        records.map((record) => JSON.stringify(record)).join(',\n'),
        '];',
        ''
    ];
    fs.writeFileSync(path.join(referenceDir, file), lines.join('\n'), 'utf8');
    console.log(`${file}: ${records.length} records`);
}

writeData('sets.js', 'Sets: [code, name, release date]', 'sets', data.sets);
writeData('cards.js',
    'Cards: [unique id, name, pitch, types, L = legendary, cost, power, defense, ' +
        'card keywords, functional text, type text, not legal in]',
    'cards', data.cards);
writeData('printings.js',
    'Printings: [card number, set code, edition, art treatment, rarity, foilings, card id, ' +
        'image, artists]',
    'printings', data.printings);

// Write the provenance of the data.
const info = {
    source: transform.SOURCE_REPO,
    branch: transform.SOURCE_BRANCH,
    commit,
    commitDate,
    built: new Date().toISOString().slice(0, 10)
};
fs.writeFileSync(path.join(referenceDir, 'info.js'), [
    '/* Provenance of the shipped reference data. Generated by tools/build-reference.mjs. */',
    `FCT.DATA.info = ${JSON.stringify(info, null, 4)};`,
    ''
].join('\n'), 'utf8');
console.log('info.js written');
